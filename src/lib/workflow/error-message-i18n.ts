/**
 * Translate a single workflow error/validation/warning message string.
 * Returns the original text unchanged if no exact or pattern match is found.
 */
export function translateWorkflowMessage(message: string | undefined, t: TranslateFn): string | undefined {
  if (!message) return message;
  const exactKey = EXACT_MESSAGE_KEYS[message];
  if (exactKey) {
    const translated = t(`errorMessages.${exactKey}`);
    if (translated) return translated;
  }
  for (const pattern of MESSAGE_PATTERNS) {
    const m = message.match(pattern.re);
    if (m) {
      const translated = t(`errorMessages.${pattern.key}`, pattern.params(m));
      if (translated) return translated;
    }
  }
  return message;
}
