/**
 * Content-derived cache key for the LibreOffice WASM assets.
 *
 * The converter requests every engine file with `?v=<version>`, and the web server serves
 * /libreoffice-wasm/* with `Cache-Control: immutable` for a year - so that version MUST change
 * whenever any of those files change, or returning visitors keep running an old soffice.js
 * against a new engine. That is exactly what happened when the assets were re-synced to
 * @matbee/libreoffice-converter 2.7.2 while the hand-maintained '20240212-4' stayed put.
 * Deriving the version from the files themselves makes it impossible to forget.
 *
 *   node scripts/libreoffice-asset-version.mjs          # print the version
 *   node scripts/libreoffice-asset-version.mjs --write  # regenerate src/lib/libreoffice/asset-version.ts
 *
 * src/__tests__/lib/libreoffice/asset-version.test.ts fails if the committed module is stale.
 */

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Order matters: it is part of the digest. */
export const LIBREOFFICE_VERSIONED_FILES = [
    'browser.worker.global.js',
    'soffice.js',
    'soffice.worker.js',
    'soffice.wasm.bin.gz',
    'soffice.data.bin.gz',
];

export const ASSET_VERSION_MODULE = 'src/lib/libreoffice/asset-version.ts';

export function computeLibreOfficeAssetVersion(rootDir) {
    const packageVersion = JSON.parse(
        readFileSync(join(rootDir, 'node_modules/@matbee/libreoffice-converter/package.json'), 'utf8')
    ).version;

    const hash = createHash('sha256');
    for (const name of LIBREOFFICE_VERSIONED_FILES) {
        let bytes = readFileSync(join(rootDir, 'public/libreoffice-wasm', name));
        // Git can check the JS glue out with CRLF on Windows; hash the LF form so every
        // platform derives the same version from the same commit.
        if (name.endsWith('.js')) {
            bytes = Buffer.from(bytes.toString('latin1').replace(/\r\n/g, '\n'), 'latin1');
        }
        hash.update(name).update('\0').update(bytes);
    }

    return { packageVersion, assetVersion: `${packageVersion}-${hash.digest('hex').slice(0, 12)}` };
}

export function renderAssetVersionModule({ packageVersion, assetVersion }) {
    return `// Generated by scripts/libreoffice-asset-version.mjs - do not edit by hand.
// Derived from the contents of public/libreoffice-wasm/, so the ?v= cache key (served with
// Cache-Control: immutable) rolls over whenever the engine files change.
// Regenerate with: node scripts/libreoffice-asset-version.mjs --write

export const LIBREOFFICE_PACKAGE_VERSION = '${packageVersion}';
export const LIBREOFFICE_ASSET_VERSION = '${assetVersion}';
`;
}

/** Writes the module only when its content actually changes (avoids needless dev rebuilds). */
export function writeLibreOfficeAssetVersionModule(rootDir) {
    const computed = computeLibreOfficeAssetVersion(rootDir);
    const target = join(rootDir, ASSET_VERSION_MODULE);
    const next = renderAssetVersionModule(computed);
    const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
    const changed = current !== next;
    if (changed) writeFileSync(target, next);
    return { ...computed, changed };
}

const invokedDirectly = (() => {
    if (!process.argv[1]) return false;
    const self = fileURLToPath(import.meta.url);
    const invoked = resolve(process.argv[1]);
    return process.platform === 'win32' ? self.toLowerCase() === invoked.toLowerCase() : self === invoked;
})();

if (invokedDirectly) {
    const rootDir = join(dirname(fileURLToPath(import.meta.url)), '..');
    if (process.argv.includes('--write')) {
        const { assetVersion, changed } = writeLibreOfficeAssetVersionModule(rootDir);
        console.log(`${changed ? 'Wrote' : 'Unchanged'} ${ASSET_VERSION_MODULE}: ${assetVersion}`);
    } else {
        console.log(computeLibreOfficeAssetVersion(rootDir).assetVersion);
    }
}
